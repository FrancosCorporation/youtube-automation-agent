const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'renders/gps-v2-review');
const hash = (f) => createHash('sha256').update(fs.readFileSync(f)).digest('hex');
const frames = [0, 115, 196, 290, 410, 510, 570, 650, 703, 723, 810, 879];
const requested = process.argv[2];
assert.ok(!requested || ['landscape', 'portrait'].includes(requested));
const reportFile = path.join(output, 'technical-qa.json');
const previous = requested && fs.existsSync(reportFile) ? JSON.parse(fs.readFileSync(reportFile)) : { masters: [] };
const report = { checkedAt: new Date().toISOString(), status: 'technical-pass-visual-review-pending', masters: previous.masters.filter((m) => m.aspect !== requested), sources: {} };
for (const retained of report.masters) assert.equal(hash(retained.file), retained.sha256, 'Previously checked MP4 changed');
for (const aspect of requested ? [requested] : ['landscape', 'portrait']) {
  const file = path.join(output, `gps-explainer-v2-${aspect}.mp4`);
  const metadata = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_format', '-show_streams', '-of', 'json', file], { encoding: 'utf8' }));
  const v = metadata.streams.find((s) => s.codec_type === 'video');
  const a = metadata.streams.find((s) => s.codec_type === 'audio');
  const [width, height] = aspect === 'landscape' ? [1920, 1080] : [1080, 1920];
  assert.equal(v.width, width); assert.equal(v.height, height);
  assert.equal(v.r_frame_rate, '24/1'); assert.equal(v.codec_name, 'h264'); assert.equal(v.pix_fmt, 'yuv420p');
  assert.equal(Number(v.nb_frames), 892); assert.equal(a.codec_name, 'aac');
  assert.ok(Math.abs(Number(metadata.format.duration) - 892 / 24) < .1);
  execFileSync('ffmpeg', ['-v', 'error', '-threads', '2', '-i', file, '-f', 'null', '-'], { stdio: 'pipe', timeout: 120000 });
  const audioPcmHash = execFileSync('ffmpeg', ['-v', 'error', '-i', file, '-map', '0:a:0', '-c:a', 'pcm_s16le', '-f', 'hash', '-hash', 'sha256', '-'], { encoding: 'utf8' }).trim();
  const dir = path.join(output, `final-${aspect}`);
  fs.mkdirSync(dir, { recursive: true });
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-threads', '2', '-i', file, '-vf', `select='${frames.map((f) => `eq(n,${f})`).join('+')}'`, '-fps_mode', 'vfr', path.join(dir, 'sample-%02d.png')], { timeout: 120000, stdio: 'pipe' });
  frames.forEach((f, i) => fs.renameSync(path.join(dir, `sample-${String(i + 1).padStart(2, '0')}.png`), path.join(dir, `frame-${String(f).padStart(3, '0')}.png`)));
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', file, '-ss', '33.75', '-frames:v', '1', '-q:v', '2', path.join(output, `poster-${aspect}.jpg`)], { stdio: 'pipe' });
  const record = { aspect, file, sha256: hash(file), bytes: fs.statSync(file).size, width, height, fps: 24, frames: 892, durationSeconds: Number(metadata.format.duration), videoCodec: v.codec_name, audioCodec: a.codec_name, audioPcmHash, decodePassed: true, sampledFrames: frames, sampleDirectory: dir };
  report.masters.push(record);
  console.log(JSON.stringify(record));
}
if (report.masters.length === 2) assert.equal(report.masters[0].audioPcmHash, report.masters[1].audioPcmHash, 'Both aspects must contain exactly the same decoded audio');
else report.status = 'partial';
for (const rel of ['src/GpsExplainerV2.tsx', 'src/ApprovedRobotPresenter.tsx', 'public/gps-explainer/narration.mp3', 'public/gps-explainer/mix-v2.m4a', 'public/gps-explainer/timeline.json', 'public/gps-explainer/captions.json', 'public/gps-explainer/audio-envelope.json', 'public/pulso-story/approved-robot-rigged.glb']) report.sources[rel] = hash(path.join(root, rel));
fs.writeFileSync(reportFile, JSON.stringify(report, null, 2) + '\n');
